//! V-LAAS.4 N2: udklipsholderen ryddes, når Grimnir låser, men kun hvis den stadig indeholder demaskeret tekst, som
//! Grimnir selv lagde der (Kopiér i Demaskér). Maskeret tekst og andre programmers indhold røres ikke (ADR D21).
//!
//! **Metoden** (logikken står i [`crate::maskering::udklip_kopieret`] og [`crate::maskering::laas_igen`]):
//! 1. Webvisningen kopierer som før (bytepræcist fra strengen; selve kopieringen er uændret) og melder et vellykket
//!    Kopiér i Demaskér til Rust (kommandoen `udklip_kopieret`). Kopiér i Maskér melder intet.
//! 2. Rust læser udklipsholderens tæller (`changeCount`). Må teksten læses uden at brugeren får besked (se nedenfor),
//!    sammenlignes den med et fingeraftryk af det demaskerede resultat, Rust selv lavede; er den anderledes, huskes
//!    intet. Tælleren læses igen bagefter; har den flyttet sig, huskes intet. Ellers huskes tælleren.
//! 3. Ved [`crate::maskering::laas_igen`] og (V-LAAS.5 N1) når programmet afslutter ([`crate::maskering::ved_afslut`]):
//!    står tælleren stadig på det tal, ryddes udklipsholderen (`clearContents`). Har nogen skrevet til den siden (også
//!    Grimnir selv, fx Kopiér i Maskér), er tælleren en anden, og den røres ikke. Rydningen læser aldrig teksten.
//!
//! **Hvorfor teksten normalt ikke læses.** Fra macOS 15.4 er standarden for den generelle udklipsholder "to ask upon
//! programmatic access" (`NSPasteboard.h`, `NSPasteboardAccessBehaviorDefault`, SDK 26/27): et program, der læser den
//! uden at brugeren har sat ind, kan få macOS til at vise en dialog. Tælleren er ikke indhold og giver ingen dialog.
//! Derfor læses teksten kun, når systemet siger, at det er tilladt uden besked (`accessBehavior == AlwaysAllow`, eller
//! før macOS 15.4, hvor ordningen ikke findes). Ellers bygger metoden på tælleren alene; hullet er beskrevet i
//! HANDOFF-V-LAAS.4.
//!
//! Teksten fra udklipsholderen gemmes ikke og logges ikke: den sammenlignes og nulstilles (Rust-kopien; `NSString`'en
//! fra AppKit kan Grimnir ikke nulstille).
//!
//! **Rust skriver selv (V-OPBYG.5 N2).** Kopiér værdi for en skjult hemmelighed i sagens indhold: værdien må ikke forbi
//! webvisningen, så Rust lægger den i udklipsholderen (`clearContents` og `setString:forType:` med
//! `NSPasteboardTypeString`) og husker tælleren bagefter som efter en demaskeret kopi; ved lås og afslutning ryddes den
//! på samme betingelse (D21). `NSString`'en, AppKit laver af værdien, kan Grimnir ikke nulstille (som ved læsning);
//! Rust-kopien nulstilles.
//!
//! **V-OPBYG.7 N1:** Rust skriver også de andre fortrolige kopier: Kopiér værdi for en almindelig værdi
//! ([`crate::maskering::sag_post_kopier`]), Kopiér resultat i Demaskér ([`crate::maskering::resultat_kopier`]) og Kopiér
//! noterne ([`crate::maskering::noter_kopier`]), alle med mærket. Kan Rust ikke skrive (ingen udklipsholder, som på
//! Windows, eller skrivningen mislykkes), svarer kommandoen falsk, og webvisningen kopierer som før og melder kopien
//! bagefter (punkt 1 ovenfor), uden mærket. Kopiér maskeret tekst, Kopiér kvittering og ⌘C på en markering er ikke
//! fortrolige og kopieres af webvisningen. `skriv_tekst` (uden mærket) er fjernet: intet brugte den efter V-OPBYG.6.
//!
//! **Fortroligt-mærket (V-OPBYG.6 N3, ADR D31).** Det, Rust selv skriver, skrives med
//! [`Udklip::skriv_fortrolig`]: teksten som almindelig tekst (`NSPasteboardTypeString`, så den kan sættes ind i andre
//! programmer som før) og på samme element konventionens mærke fra nspasteboard.org: [`FORTROLIG`]
//! (`org.nspasteboard.ConcealedType`, "content that should be treated as confidential"; programmer, der husker
//! udklipsholderens historik, kan springe det over) og [`KILDE`] (`org.nspasteboard.source` med Grimnirs bundle-id,
//! [`BUNDLE_ID`]). Mærket har intet indhold (konventionen bruger kun dets tilstedeværelse); det skrives som en tom streng
//! med `setString:forType:`, der ifølge `NSPasteboard.h` (SDK'et) virker på udklipsholderens første element, samme
//! element som teksten. Lykkes mærket ikke, ryddes udklipsholderen igen, og svaret er falsk: en hemmelighed ligger aldrig
//! der uden mærket. `TransientType` og `AutoGeneratedType` bruges ikke: værdien står der, til brugeren sætter den ind, og
//! brugeren har selv valgt Kopiér. Lås og afslutning rydder som før (D21).
//!
//! **Windows** har endnu ingen udgave (B4): [`platformens`] svarer `None`, og intet ryddes eller skrives. En Windows-udgave
//! kræver `OpenClipboard`/`EmptyClipboard`/`SetClipboardData(CF_UNICODETEXT)` og `GetClipboardSequenceNumber` som tæller
//! (en binding, Grimnir ikke har i dag); se HANDOFF-V-OPBYG.5, Fase A 2.
//!
//! `unsafe` står kun her (og i `laas.rs` og `notifikationer.rs`), hver gang med `SAFETY:`.
#![allow(unsafe_code)]

use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::Mutex;

use zeroize::Zeroizing;

/// V-OPBYG.6 N3: konventionens mærke for fortroligt indhold (nspasteboard.org, "ConcealedType").
pub const FORTROLIG: &str = "org.nspasteboard.ConcealedType";
/// V-OPBYG.6 N3: konventionens mærke for kilden (nspasteboard.org); indholdet er bundle-id'et som UTF-8.
pub const KILDE: &str = "org.nspasteboard.source";
/// Grimnirs bundle-id (`identifier` i `tauri.conf.json`; testen `opbyg6` holder dem ens).
pub const BUNDLE_ID: &str = "com.wi24rd.grimnir";
/// Typen for almindelig tekst (værdien af `NSPasteboardTypeString`). Bruges af [`HukommelsesUdklip`] til at huske, hvilke
/// typer der blev skrevet.
pub const TEKST_TYPE: &str = "public.utf8-plain-text";

/// Udklipsholderens tekst, som Grimnir ser den.
pub enum Indhold {
    /// Teksten (nulstilles, når den slippes).
    Tekst(Zeroizing<String>),
    /// Der er ingen tekst.
    Ingen,
    /// Teksten må ikke læses uden at brugeren får besked; kun tælleren kan bruges.
    MaaIkkeLaeses,
}

/// Den generelle udklipsholder. Den rigtige udgave er macOS' `NSPasteboard` ([`platformens`]); tests bruger
/// [`HukommelsesUdklip`] og rører aldrig den rigtige.
pub trait Udklip: Send + Sync {
    /// Tælleren, der går op, hver gang nogen skriver til udklipsholderen (`changeCount`). `None`: kan ikke læses.
    fn taeller(&self) -> Option<isize>;
    /// Teksten, hvis den må læses uden besked til brugeren.
    fn tekst(&self) -> Indhold;
    /// Rydder udklipsholderen.
    fn ryd(&self);
    /// V-OPBYG.6 N3: lægger `tekst` i udklipsholderen i stedet for det, der stod der (tælleren går op), som almindelig
    /// tekst og med fortroligt-mærket ([`FORTROLIG`]) og kilden ([`KILDE`]) på samme element. Falsk, hvis teksten eller
    /// mærket ikke kunne skrives (så ligger teksten der ikke). Standarden kan ikke skrive (en udklipsholder, der kun læser
    /// og rydder); macOS' og testenes skriver. (V-OPBYG.7 N1: `skriv_tekst` uden mærket er fjernet; intet brugte den.)
    fn skriv_fortrolig(&self, _tekst: &str) -> bool {
        false
    }
}

impl<T: Udklip + ?Sized> Udklip for std::sync::Arc<T> {
    fn taeller(&self) -> Option<isize> {
        (**self).taeller()
    }
    fn tekst(&self) -> Indhold {
        (**self).tekst()
    }
    fn ryd(&self) {
        (**self).ryd()
    }
    fn skriv_fortrolig(&self, tekst: &str) -> bool {
        (**self).skriv_fortrolig(tekst)
    }
}

/// En udklipsholder i hukommelsen til tests: en tæller og en tekst. `laesbar` afgør, om teksten må læses (som
/// `AlwaysAllow` på macOS) eller ej (standarden).
pub struct HukommelsesUdklip {
    indhold: Mutex<(isize, Option<String>)>,
    /// V-OPBYG.6 N3: typerne (og deres indhold) på det, der står der nu: (type, indhold). Tom, når den er ryddet.
    typer: Mutex<Vec<(String, String)>>,
    laesbar: bool,
    /// V-LAAS.5: antal kald af [`Udklip::tekst`] (en læsning, der på macOS kan give en dialog).
    laesninger: AtomicUsize,
    /// V-OPBYG.5: antal gange, Grimnir selv har skrevet ([`Udklip::skriv_fortrolig`]).
    skrivninger: AtomicUsize,
    /// V-OPBYG.5: sand: skrivningen mislykkes (som en udklipsholder, der ikke tager imod).
    afviser: std::sync::atomic::AtomicBool,
}

impl HukommelsesUdklip {
    /// En tom udklipsholder; `laesbar`: teksten må læses uden besked.
    pub fn ny(laesbar: bool) -> Self {
        HukommelsesUdklip {
            indhold: Mutex::new((0, None)),
            typer: Mutex::new(Vec::new()),
            laesbar,
            laesninger: AtomicUsize::new(0),
            skrivninger: AtomicUsize::new(0),
            afviser: std::sync::atomic::AtomicBool::new(false),
        }
    }

    /// V-OPBYG.5: antal gange, Grimnir selv har skrevet til udklipsholderen ([`Udklip::skriv_fortrolig`]).
    pub fn skrivninger(&self) -> usize {
        self.skrivninger.load(Ordering::SeqCst)
    }

    /// V-OPBYG.5: fra nu af mislykkes Grimnirs skrivning (tælleren og teksten røres ikke).
    pub fn afvis_skrivning(&self) {
        self.afviser.store(true, Ordering::SeqCst);
    }

    fn laas(&self) -> std::sync::MutexGuard<'_, (isize, Option<String>)> {
        self.indhold.lock().unwrap_or_else(|e| e.into_inner())
    }

    /// Nogen (webvisningen eller et andet program) skriver tekst: tælleren går op. Kun almindelig tekst, intet mærke.
    pub fn skriv(&self, tekst: &str) {
        self.skriv_med(tekst, &[]);
    }

    /// Skriver teksten (almindelig tekst) og mærkerne på samme element; tælleren går op én gang.
    fn skriv_med(&self, tekst: &str, maerker: &[(&str, &str)]) {
        let mut g = self.laas();
        g.0 += 1;
        g.1 = Some(tekst.to_string());
        let mut t = self.typer.lock().unwrap_or_else(|e| e.into_inner());
        *t = std::iter::once((TEKST_TYPE.to_string(), tekst.to_string()))
            .chain(maerker.iter().map(|(a, b)| (a.to_string(), b.to_string())))
            .collect();
    }

    /// V-OPBYG.6 N3: typerne på det, der står der nu, med indhold (testens øjne): teksten under [`TEKST_TYPE`] og evt.
    /// mærkerne. Tom efter en rydning.
    pub fn typer_nu(&self) -> Vec<(String, String)> {
        self.typer.lock().unwrap_or_else(|e| e.into_inner()).clone()
    }

    /// Teksten nu (testens øjne; uden for traitet).
    pub fn nu(&self) -> Option<String> {
        self.laas().1.clone()
    }

    /// Tælleren nu (testens øjne).
    pub fn taeller_nu(&self) -> isize {
        self.laas().0
    }

    /// V-LAAS.5: antal gange, Grimnir har bedt om teksten ([`Udklip::tekst`]), uanset om den måtte læses.
    pub fn laesninger(&self) -> usize {
        self.laesninger.load(Ordering::SeqCst)
    }
}

impl Udklip for HukommelsesUdklip {
    fn taeller(&self) -> Option<isize> {
        Some(self.laas().0)
    }
    fn tekst(&self) -> Indhold {
        self.laesninger.fetch_add(1, Ordering::SeqCst);
        if !self.laesbar {
            return Indhold::MaaIkkeLaeses;
        }
        match &self.laas().1 {
            Some(t) => Indhold::Tekst(Zeroizing::new(t.clone())),
            None => Indhold::Ingen,
        }
    }
    fn ryd(&self) {
        let mut g = self.laas();
        g.0 += 1;
        g.1 = None;
        self.typer.lock().unwrap_or_else(|e| e.into_inner()).clear();
    }
    fn skriv_fortrolig(&self, tekst: &str) -> bool {
        self.skrivninger.fetch_add(1, Ordering::SeqCst);
        if self.afviser.load(Ordering::SeqCst) {
            return false;
        }
        self.skriv_med(tekst, &[(FORTROLIG, ""), (KILDE, BUNDLE_ID)]);
        true
    }
}

/// Platformens udklipsholder: `NSPasteboard.generalPasteboard` på macOS; ingen andre steder endnu (B4).
pub fn platformens() -> Option<Box<dyn Udklip>> {
    #[cfg(target_os = "macos")]
    {
        Some(Box::new(mac::MacUdklip))
    }
    #[cfg(not(target_os = "macos"))]
    {
        None
    }
}

#[cfg(target_os = "macos")]
mod mac {
    use objc2::rc::autoreleasepool;
    use objc2_app_kit::{NSPasteboard, NSPasteboardAccessBehavior, NSPasteboardTypeString};
    use objc2_foundation::NSString;
    use zeroize::Zeroizing;

    use super::{Indhold, Udklip, BUNDLE_ID, FORTROLIG, KILDE};

    /// `NSPasteboard.generalPasteboard`. Hentes ved hvert kald (objektet holdes ikke mellem tråde).
    pub struct MacUdklip;

    impl Udklip for MacUdklip {
        fn taeller(&self) -> Option<isize> {
            autoreleasepool(|_| Some(NSPasteboard::generalPasteboard().changeCount()))
        }

        fn tekst(&self) -> Indhold {
            autoreleasepool(|_| {
                let pb = NSPasteboard::generalPasteboard();
                // `accessBehavior` findes fra macOS 15.4; før det spørger macOS ikke ved programmatisk læsning.
                if objc2::available!(macos = 15.4) && pb.accessBehavior() != NSPasteboardAccessBehavior::AlwaysAllow {
                    return Indhold::MaaIkkeLaeses;
                }
                // SAFETY: `NSPasteboardTypeString` er en konstant `NSString`, som AppKit eksporterer og aldrig ændrer;
                // at læse en `extern static` er `unsafe`, fordi Rust ikke kan se, at den er initialiseret. AppKit er
                // linket (featuren `NSPasteboard`), og værdien er en gyldig, uforanderlig reference hele programmets tid.
                let type_ = unsafe { NSPasteboardTypeString };
                match pb.stringForType(type_) {
                    Some(s) => Indhold::Tekst(Zeroizing::new(s.to_string())),
                    None => Indhold::Ingen,
                }
            })
        }

        fn ryd(&self) {
            autoreleasepool(|_| {
                NSPasteboard::generalPasteboard().clearContents();
            });
        }

        /// V-OPBYG.6 N3: teksten som almindelig tekst og på samme (første) element fortroligt-mærket og kilden
        /// (`NSPasteboard.h`: `setString:forType:` virker på udklipsholderens første element). Lykkes mærket ikke, ryddes
        /// udklipsholderen igen, så værdien ikke ligger der umærket. Kun oversat; prøves i programmet (HANDOFF).
        fn skriv_fortrolig(&self, tekst: &str) -> bool {
            autoreleasepool(|_| {
                let pb = NSPasteboard::generalPasteboard();
                pb.clearContents();
                let s = NSString::from_str(tekst);
                // SAFETY: som i `tekst`: `NSPasteboardTypeString` er en konstant `NSString` fra AppKit, gyldig og
                // uforanderlig hele programmets tid.
                let type_ = unsafe { NSPasteboardTypeString };
                if !pb.setString_forType(&s, type_) {
                    pb.clearContents();
                    return false;
                }
                let maerke = pb.setString_forType(&NSString::from_str(""), &NSString::from_str(FORTROLIG));
                let kilde = pb.setString_forType(&NSString::from_str(BUNDLE_ID), &NSString::from_str(KILDE));
                if !(maerke && kilde) {
                    pb.clearContents();
                    return false;
                }
                true
            })
        }
    }
}
